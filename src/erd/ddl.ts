/**
 * SQL DDL from an ER diagram, per database. Pure module: no `vscode` imports.
 */
import { sqlName } from '../codegen/entityGenerator';
import { DbKind, dialect } from '../model/types';
import { ErdColumn, ErdDocument, ErdEntity, foldIdentifier, nativeType } from './erdModel';

export interface DdlOptions {
  /** Prefix tables with their schema (off by default: the script runs in the current schema). */
  qualifySchemas?: boolean;
  /** Emit table and column comments (default true). */
  comments?: boolean;
}

const IDENTITY_SQL: Partial<Record<DbKind, string>> = {
  postgresql: 'generated by default as identity',
  oracle: 'generated by default as identity',
  db2: 'generated by default as identity',
  h2: 'generated by default as identity',
  hsqldb: 'generated by default as identity',
  derby: 'generated by default as identity',
  firebird: 'generated by default as identity',
  mysql: 'auto_increment',
  mariadb: 'auto_increment',
  sqlserver: 'identity(1,1)',
};

/** Quotes an identifier for a database when it needs quoting (reserved word, special characters, case). */
export function quoteIdentifier(name: string, kind: DbKind): string {
  const q = sqlName(name, kind);
  if (!q.startsWith('"')) {
    return q;
  }
  const inner = q.slice(1, -1);
  if (kind === 'mysql' || kind === 'mariadb') {
    return `\`${inner.replace(/`/g, '``')}\``;
  }
  if (kind === 'sqlserver') {
    return `[${inner.replace(/]/g, ']]')}]`;
  }
  return `"${inner.replace(/"/g, '""')}"`;
}

const literal = (s: string) => `'${s.replace(/'/g, "''")}'`;

/** Orders entities so that referenced tables come first (cycles keep their input order). */
export function dependencyOrder(doc: ErdDocument): ErdEntity[] {
  const byId = new Map(doc.entities.map(e => [e.id, e]));
  const out: ErdEntity[] = [];
  const state = new Map<string, 'visiting' | 'done'>();
  const visit = (e: ErdEntity) => {
    if (state.get(e.id)) {
      return;
    }
    state.set(e.id, 'visiting');
    for (const r of doc.relationships) {
      const target = r.from === e.id && r.to !== e.id ? byId.get(r.to) : undefined;
      if (target && state.get(target.id) !== 'visiting') {
        visit(target);
      }
    }
    state.set(e.id, 'done');
    out.push(e);
  };
  doc.entities.forEach(visit);
  return out;
}

export function generateDdl(doc: ErdDocument, kind: DbKind = doc.dialect, opts: DdlOptions = {}): string {
  const comments = opts.comments ?? true;
  const fold = (s: string) => foldIdentifier(s, kind);
  const id = (s: string) => quoteIdentifier(fold(s), kind);
  const tableRef = (e: ErdEntity) => (opts.qualifySchemas && e.schema ? `${id(e.schema)}.${id(e.table)}` : id(e.table));
  const constraint = (prefix: string, table: string, cols: string[]) => id([prefix, table, ...cols].join('_').slice(0, 60));
  const useNative = doc.nativeDialect === kind;
  const byId = new Map(doc.entities.map(e => [e.id, e]));
  const sqlite = kind === 'sqlite';
  const mysql = kind === 'mysql' || kind === 'mariadb';

  const out: string[] = [`-- ${doc.name}: schema for ${dialect(kind).label}, generated by JPA Power Tools`, ''];
  const after: string[] = [];
  const commentSql: string[] = [];

  for (const e of dependencyOrder(doc)) {
    if (e.kind === 'view') {
      out.push(`-- ${e.table} is a view; its definition is not part of the diagram.`, '');
      continue;
    }
    const pk = e.columns.filter(c => c.primaryKey);
    const sqliteRowid = sqlite && pk.length === 1 && pk[0].autoIncrement;
    const lines: string[] = [];
    for (const c of e.columns) {
      lines.push(`  ${columnDefinition(c, e, pk.length === 1)}`);
    }
    if (pk.length && !sqliteRowid) {
      lines.push(`  constraint ${constraint('pk', e.table, [])} primary key (${pk.map(c => id(c.name)).join(', ')})`);
    }
    for (const c of e.columns.filter(x => x.unique && !x.primaryKey)) {
      lines.push(`  constraint ${constraint('uk', e.table, [c.name])} unique (${id(c.name)})`);
    }
    for (const r of doc.relationships.filter(x => x.from === e.id)) {
      const target = byId.get(r.to);
      if (!target) {
        continue;
      }
      if (r.oneToOne && r.columns.length && !e.columns.some(c => c.unique && r.columns.length === 1 && c.name === r.columns[0])
        && !(pk.length === r.columns.length && pk.every(p => r.columns.includes(p.name)))) {
        lines.push(`  constraint ${constraint('uk', e.table, r.columns)} unique (${r.columns.map(id).join(', ')})`);
      }
      const fk = `constraint ${constraint('fk', e.table, r.columns)} foreign key (${r.columns.map(id).join(', ')}) references ${tableRef(target)} (${r.refColumns.map(id).join(', ')})`;
      if (sqlite) {
        lines.push(`  ${fk}`);
      } else {
        after.push(`alter table ${tableRef(e)} add ${fk};`);
      }
    }
    const tableComment = comments && mysql && e.comment ? ` comment = ${literal(e.comment)}` : '';
    out.push(`create table ${tableRef(e)} (`, lines.join(',\n'), `)${tableComment};`, '');

    if (comments) {
      commentSql.push(...commentStatements(e));
    }
  }
  if (after.length) {
    out.push(...after, '');
  }
  if (commentSql.length) {
    out.push(...commentSql, '');
  }
  return out.join('\n').replace(/\n{3,}/g, '\n\n').trimEnd() + '\n';

  function columnDefinition(c: ErdColumn, e: ErdEntity, singlePk: boolean): string {
    const type = useNative && c.nativeType ? c.nativeType : nativeType(c, kind);
    const parts = [id(c.name)];
    const identity = c.autoIncrement && c.primaryKey && singlePk;
    if (sqlite && identity) {
      return `${id(c.name)} integer primary key autoincrement`;
    }
    parts.push(type);
    if (identity && IDENTITY_SQL[kind]) {
      parts.push(IDENTITY_SQL[kind]!);
    }
    if (!c.nullable || c.primaryKey) {
      parts.push('not null');
    }
    if (comments && mysql && c.comment) {
      parts.push(`comment ${literal(c.comment)}`);
    }
    void e;
    return parts.join(' ');
  }

  function commentStatements(e: ErdEntity): string[] {
    const stmts: string[] = [];
    if (kind === 'sqlserver') {
      const schema = literal(e.schema || 'dbo');
      if (e.comment) {
        stmts.push(`exec sp_addextendedproperty 'MS_Description', ${literal(e.comment)}, 'SCHEMA', ${schema}, 'TABLE', ${literal(fold(e.table))};`);
      }
      for (const c of e.columns.filter(x => x.comment)) {
        stmts.push(`exec sp_addextendedproperty 'MS_Description', ${literal(c.comment!)}, 'SCHEMA', ${schema}, 'TABLE', ${literal(fold(e.table))}, 'COLUMN', ${literal(fold(c.name))};`);
      }
      return stmts;
    }
    if (mysql || sqlite || kind === 'derby') {
      return stmts; // MySQL comments are inline; SQLite and Derby have none
    }
    if (e.comment) {
      stmts.push(`comment on table ${tableRef(e)} is ${literal(e.comment)};`);
    }
    for (const c of e.columns.filter(x => x.comment)) {
      stmts.push(`comment on column ${tableRef(e)}.${id(c.name)} is ${literal(c.comment!)};`);
    }
    return stmts;
  }
}

/** Splits a DDL script into executable statements (for running it through a driver). */
export function splitStatements(ddl: string): string[] {
  return ddl.split(/;\s*(?:\n|$)/).map(s => s.replace(/^(\s*--.*\n)+/g, '').trim()).filter(s => s && !s.startsWith('--'));
}

/** Next Flyway-style migration name in a folder, e.g. `V3__create_shop_schema.sql`. */
export function nextMigrationName(existing: string[], description: string): string {
  const versions = existing.map(f => /^V(\d+)(?:[._]\d+)*__/i.exec(f)?.[1]).filter(Boolean).map(Number);
  const next = versions.length ? Math.max(...versions) + 1 : 1;
  const slug = description.toLowerCase().replace(/[^a-z0-9]+/g, '_').replace(/^_|_$/g, '') || 'schema';
  return `V${next}__${slug}.sql`;
}
