import { GeneratorPanel } from '../../webview/GeneratorPanel';
import { screenshot } from './screenshot';

const sleep = (ms: number) => new Promise(r => setTimeout(r, ms));

async function waitFor<T>(fn: () => T | undefined | Promise<T | undefined>, timeoutMs = 30_000): Promise<T> {
  const end = Date.now() + timeoutMs;
  for (;;) {
    const v = await fn();
    if (v) {
      return v;
    }
    if (Date.now() > end) {
      throw new Error('Timed out waiting for condition');
    }
    await sleep(100);
  }
}

function reachable(port: number): Promise<boolean> {
  return new Promise(resolve => {
    const s = net.connect({ host: '127.0.0.1', port }, () => { s.destroy(); resolve(true); });
    s.on('error', () => resolve(false));
    s.setTimeout(1500, () => { s.destroy(); resolve(false); });
  });
}

suite('ER diagrams in VS Code', () => {
  let api: JpaPowerToolsApi;
  const root = vscode.workspace.workspaceFolders![0].uri.fsPath;
  const erdDir = path.join(root, 'erd');

  suiteSetup(async () => {
    api = await vscode.extensions.getExtension<JpaPowerToolsApi>('izzyjere.jpa-powertools')!.activate();
    fs.rmSync(erdDir, { recursive: true, force: true });
  });

  suiteTeardown(async () => {
    await vscode.commands.executeCommand('workbench.action.revertAndCloseActiveEditor');
    await vscode.commands.executeCommand('workbench.action.closeAllEditors');
    try {
      fs.rmSync(erdDir, { recursive: true, force: true, maxRetries: 10, retryDelay: 200 });
    } catch {
      // Windows may still hold the folder open; it is recreated cleanly by the next run.
    }
  });

  const editorFor = (file: string) => ErdEditorProvider.editors.get(vscode.Uri.file(file).toString());
  const loadedDoc = async (file: string) => {
    const editor = await waitFor(() => editorFor(file));
    const load = await waitFor(() => editor.posted.get('load') as { doc: ErdDocument } | undefined);
    return { editor, doc: load.doc };
  };

  test('opens a diagram of the workspace entities in the ER diagram editor', async () => {
    await vscode.commands.executeCommand('jpaPowertools.erdFromEntities');
    const file = path.join(erdDir, 'entities.erd.json');
    await waitFor(() => fs.existsSync(file));
    const tab = await waitFor(() => vscode.window.tabGroups.all.flatMap(g => g.tabs)
      .find(t => t.input instanceof vscode.TabInputCustom && t.input.viewType === ErdEditorProvider.viewType));
    assert.strictEqual(tab.label, 'entities.erd.json');

    const { doc } = await loadedDoc(file);
    assert.deepStrictEqual(doc.entities.map(e => e.table).sort(), ['customers', 'order_items', 'orders', 'product_tags', 'products']);
    const orders = doc.entities.find(e => e.table === 'orders')!;
    assert.strictEqual(orders.className, 'PurchaseOrder');
    assert.ok(doc.relationships.some(r => r.field === 'customer' && r.inverseField === 'orders'));
    // The canvas places the tables and writes the positions back into the document.
    const placed = await waitFor(() => {
      const saved = JSON.parse(vscode.workspace.textDocuments.find(d => d.uri.fsPath === file)?.getText() ?? '{}') as ErdDocument;
      return saved.entities?.every(e => typeof e.x === 'number') ? saved : undefined;
    }, 15_000);
    assert.ok(placed.entities.length === 5);
    await sleep(1500);
    screenshot('08-erd-entities');
  });

  test('edits from the canvas go through the document (undo/redo)', async () => {
    const file = path.join(erdDir, 'entities.erd.json');
    const { editor } = await loadedDoc(file);
    const textDoc = vscode.workspace.textDocuments.find(d => d.uri.fsPath === file)!;
    const doc = JSON.parse(textDoc.getText()) as ErdDocument;
    doc.entities.find(e => e.table === 'customers')!.comment = 'Edited on the canvas';
    await editor.handle({ type: 'edit', doc, label: 'Edit' });
    assert.match(textDoc.getText(), /Edited on the canvas/);
    assert.ok(textDoc.isDirty);
    await vscode.commands.executeCommand('undo');
    await waitFor(() => !/Edited on the canvas/.test(textDoc.getText()) || undefined, 5000);
  });

  test('generates SQL DDL and opens the entity generator from the diagram', async () => {
    const file = path.join(erdDir, 'entities.erd.json');
    const { editor } = await loadedDoc(file);
    await editor.handle({ type: 'generateSql', dialect: 'oracle' });
    const sql = await waitFor(() => vscode.workspace.textDocuments.find(d => d.languageId === 'sql' && /generated by JPA Power Tools/.test(d.getText())));
    assert.match(sql.getText(), /create table CUSTOMERS \(\n {2}ID number\(19\) generated by default as identity not null,/);
    assert.match(sql.getText(), /alter table ORDERS add constraint FK_ORDERS_CUSTOMER_ID foreign key \(CUSTOMER_ID\) references CUSTOMERS \(ID\);/);

    await vscode.window.showTextDocument(vscode.Uri.file(file));
    await editor.handle({ type: 'generateEntities' });
    const panel = await waitFor(() => GeneratorPanel.panels().find(p => p.lastPosted.has('init') || true));
    const init = await waitFor(() => panel.lastPosted.get('init') as { tables: Array<{ name: string }>; preselected: string[] } | undefined);
    assert.ok(init.tables.some(t => t.name === 'orders'));
    assert.ok(init.preselected.includes('customers'));
    await panel.handle({ type: 'preview', tables: ['orders', 'customers'], focus: 'orders', options: (panel.lastPosted.get('init') as { options: never }).options, seq: 1 });
    const preview = panel.lastPosted.get('preview') as { focusFiles: Array<{ className: string; content: string }> };
    assert.strictEqual(preview.focusFiles[0].className, 'PurchaseOrder', 'class names from the diagram are kept');
    assert.match(preview.focusFiles[0].content, /private Customer customer;/);
    await vscode.commands.executeCommand('workbench.action.closeActiveEditor');
  });

  test('diagrams a live database schema', async function () {
    if (!(await reachable(55432))) {
      this.skip();
    }
    await api.store.save({
      id: 'erd-pg', name: 'Shop ERD', kind: 'postgresql', host: 'localhost', port: 55432, database: 'shop', user: 'postgres', ssl: false, savePassword: true,
    }, 'secret');
    try {
      const conn = (await api.explorer.getChildren()).find(n => n.type === 'connection' && n.config.id === 'erd-pg')!;
      const [schema] = await api.explorer.getChildren(conn);
      await vscode.commands.executeCommand('jpaPowertools.erdFromDatabase', schema);
      const file = path.join(erdDir, 'shop-erd-public.erd.json');
      const { doc } = await loadedDoc(file);
      assert.ok(doc.entities.length >= 9);
      assert.deepStrictEqual(doc.source, { type: 'database', connectionId: 'erd-pg', connection: 'Shop ERD', schema: 'public' });
      assert.ok(doc.relationships.some(r => r.from === 'public.orders' && r.to === 'public.customers'));
      await sleep(2000);
      screenshot('09-erd-database');
    } finally {
      await api.store.remove('erd-pg');
    }
  });
});
